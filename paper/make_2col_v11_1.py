"""make_2col_v11_1.py — buat main_v11_1_2col.tex dari main_v11_1.tex.

HANYA tata letak (mengikuti pola proj-final/paper/main_journal_2col.tex):
  * \\documentclass[preprint,12pt]{elsarticle}
       -> \\documentclass[final,5p,times,twocolumn]{elsarticle}
    (TANPA opsi authoryear; gaya sitasi bernomor dipertahankan)
  * semua figure  -> figure*  dan width=\\linewidth -> width=\\textwidth
  * semua table   -> table*   (yang sudah table* dibiarkan)
  * lingkungan paperhighlights dibuang dari badan dokumen
Teks ilmiah, angka, sitasi, dan isi tabel TIDAK disentuh.

python make_2col_v11_1.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "main_v11_1.tex")
DST = os.path.join(HERE, "main_v11_1_2col.tex")

t = open(SRC, encoding="utf-8", newline="").read()
log = []

old_cls = re.search(r"\\documentclass\[[^\]]*\]\{elsarticle\}", t)
t = t.replace(old_cls.group(0), r"\documentclass[final,5p,times,twocolumn]{elsarticle}", 1)
log.append(f"documentclass: {old_cls.group(0)} -> [final,5p,times,twocolumn]")

n_fig = len(re.findall(r"\\begin\{figure\}", t))
t = t.replace(r"\begin{figure}", r"\begin{figure*}").replace(r"\end{figure}", r"\end{figure*}")
log.append(f"figure -> figure*: {n_fig}")

n_w = len(re.findall(r"width=\\linewidth", t))
t = t.replace(r"width=\linewidth", r"width=\textwidth")
log.append(f"width=\\linewidth -> \\textwidth: {n_w}")

n_tab = len(re.findall(r"\\begin\{table\}", t))
t = t.replace(r"\begin{table}", r"\begin{table*}").replace(r"\end{table}", r"\end{table*}")
log.append(f"table -> table*: {n_tab}")

m = re.search(r"\\begin\{paperhighlights\}.*?\\end\{paperhighlights\}", t, re.S)
if m:
    t = t.replace(m.group(0), "% highlights dibuang pada versi dua kolom "
                              "(dikirim sebagai berkas Highlights terpisah)\n", 1)
    log.append("paperhighlights: dibuang dari badan dokumen")

head = ("% TWO-COLUMN VERSION generated by make_2col_v11_1.py; do not edit.\n"
        "% Layout only: document class, float widths, highlights removed.\n"
        "% Scientific text, numbers, citations and table contents are identical to\n"
        "% main_v11_1.tex.\n")
t = head + t
open(DST, "w", encoding="utf-8", newline="").write(t)
print("tulis", DST)
for x in log:
    print(" -", x)
